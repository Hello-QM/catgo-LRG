/**
 * Message handler around the wfn-wasm module (Rust port of Multiwfn's
 * wavefunction loading and density evaluation). Runs inside each
 * wfn.worker.ts, or on the main thread when workers are unavailable.
 */

export interface GridSpec {
  /** Bohr */
  origin: [number, number, number];
  /** Bohr */
  spacing: [number, number, number];
  dims: [number, number, number];
}

export type GridKind =
  | `orbital`
  | `density`
  | `gradient`
  | `laplacian`
  | `sl2r`
  | `rdg`
  | `iri_sl2r`;

export type CoreRequest =
  | { op: `load`; key: string; text: string; filename: string }
  | { op: `grid`; key: string; quality: string }
  | {
    op: `evaluate`;
    key: string;
    kind: GridKind;
    orbital: number;
    grid: GridSpec;
    ix0: number;
    ix1: number;
  }
  | { op: `drop`; key: string };

export type CoreResponse =
  | { info_json: string; trace_ps: number }
  | { grid: GridSpec }
  | { data: Float64Array }
  | { ok: true };

interface WfnHandle {
  info_json(): string;
  trace_ps(): number;
  grid_json(quality: string): string;
  evaluate(
    kind: string,
    orbital: number,
    grid_json: string,
    ix0: number,
    ix1: number,
  ): Float64Array;
  free(): void;
}

export interface WfnModule {
  default: (input: { module_or_path: unknown }) => Promise<unknown>;
  WfnHandle: new (text: string, filename: string) => WfnHandle;
}

let module_promise: Promise<WfnModule> | null = null;

/** Use an already initialised module (tests run it from Node without fetch). */
export function use_wfn_module(mod: WfnModule): void {
  module_promise = Promise.resolve(mod);
}

function wasm_module(): Promise<WfnModule> {
  module_promise ??= (async () => {
    // Generated by `pnpm build:wasm` (scripts/build-wasm.mjs, target "wfn")
    // @ts-ignore — generated WASM package
    const mod =
      (await import(`./wfn-wasm-pkg/wfn_wasm.js`)) as unknown as WfnModule;
    // @ts-ignore — Vite asset URL of the generated binary
    const url = (await import(`./wfn-wasm-pkg/wfn_wasm_bg.wasm?url`))
      .default as string;
    await mod.default({ module_or_path: url });
    return mod;
  })();
  return module_promise;
}

const handles = new Map<string, WfnHandle>();

function handle_for(key: string): WfnHandle {
  const h = handles.get(key);
  if (!h) throw new Error(`Wavefunction ${key} is not loaded`);
  return h;
}

export async function run_core(req: CoreRequest): Promise<CoreResponse> {
  if (req.op === `drop`) {
    handles.get(req.key)?.free();
    handles.delete(req.key);
    return { ok: true };
  }
  const mod = await wasm_module();
  if (req.op === `load`) {
    let h = handles.get(req.key);
    if (!h) {
      h = new mod.WfnHandle(req.text, req.filename);
      handles.set(req.key, h);
    }
    return { info_json: h.info_json(), trace_ps: h.trace_ps() };
  }
  const h = handle_for(req.key);
  if (req.op === `grid`) return { grid: JSON.parse(h.grid_json(req.quality)) };
  return {
    data: h.evaluate(
      req.kind,
      req.orbital,
      JSON.stringify(req.grid),
      req.ix0,
      req.ix1,
    ),
  };
}
