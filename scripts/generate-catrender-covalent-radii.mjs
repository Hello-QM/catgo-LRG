import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const inputPath = `src/lib/element/data.ts`
const outputPath = `extensions/catrender-wasm/src/element_data.rs`
const expectedBlob = `d28d96c24f29a98944f1ae806f5c002266075c86`
const historicalCommit = `4da4da53631c057bf486a996f463201cf707d8a6`
const historicalPath = `${historicalCommit}:${inputPath}`
const licensePath = `third_party/licenses/MatterViz-MIT.txt`

const root = process.cwd()
const input = readFileSync(resolve(root, inputPath))
const blob = execFileSync(`git`, [`hash-object`, inputPath], {
  cwd: root,
  encoding: `utf8`,
}).trim()

if (blob !== expectedBlob) {
  throw new Error(`${inputPath} Git blob ${blob} does not match audited ${expectedBlob}`)
}

const historical = execFileSync(`git`, [`show`, historicalPath], {
  cwd: root,
  encoding: null,
})
if (!input.equals(historical)) {
  throw new Error(`${inputPath} differs from audited historical source ${historicalPath}`)
}

const source = input.toString(`utf8`)
if (
  !source.includes(`export default [`) ||
  !source.endsWith(`] satisfies ChemicalElement[]\n`)
) {
  throw new Error(`${inputPath} has an unexpected wrapper`)
}

const blocks = [...source.matchAll(/^  \{\n([\s\S]*?)^  \},?$/gm)].map(
  (match) => match[1],
)
const symbolCount = [...source.matchAll(/^    symbol: /gm)].length
const radiusCount = [...source.matchAll(/^    covalent_radius: /gm)].length
if (blocks.length < 118 || blocks.length !== symbolCount || blocks.length !== radiusCount) {
  throw new Error(
    `${inputPath} must contain at least 118 objects with one symbol and radius each`,
  )
}

const seen = new Set()
const radii = []
for (const [index, block] of blocks.entries()) {
  const symbols = [...block.matchAll(/^    symbol: `([A-Z][a-z]?)`,$/gm)]
  const radiusValues = [
    ...block.matchAll(
      /^    covalent_radius: (null|-?(?:\d+(?:\.\d+)?|\.\d+)),$/gm,
    ),
  ]
  if (symbols.length !== 1 || radiusValues.length !== 1) {
    throw new Error(`element object ${index + 1} has an unexpected symbol/radius shape`)
  }

  const symbolMatch = symbols[0]
  const radiusMatch = radiusValues[0]
  if ((symbolMatch.index ?? -1) >= (radiusMatch.index ?? -1)) {
    throw new Error(`element object ${index + 1} does not place radius after symbol`)
  }

  const symbol = symbolMatch[1]
  if (seen.has(symbol)) throw new Error(`duplicate element symbol ${symbol}`)
  seen.add(symbol)

  if (radiusMatch[1] === `null`) continue
  const radius = Number(radiusMatch[1])
  if (!Number.isFinite(radius)) throw new Error(`non-finite radius for ${symbol}`)
  const rustLiteral = radiusMatch[1].includes(`.`)
    ? radiusMatch[1]
    : `${radiusMatch[1]}.0`
  radii.push([symbol, rustLiteral])
}

radii.sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))

const arms = radii
  .map(([symbol, radius]) => `        "${symbol}" => Some(${radius}),`)
  .join(`\n`)
const output = `// @generated by scripts/generate-catrender-covalent-radii.mjs; do not edit.
// Input: src/lib/element/data.ts
// Input Git blob: d28d96c24f29a98944f1ae806f5c002266075c86
// Byte-identical historical source: 4da4da53631c057bf486a996f463201cf707d8a6:src/lib/element/data.ts
// License notice: third_party/licenses/MatterViz-MIT.txt

pub(crate) fn covalent_radius(symbol: &str) -> Option<f64> {
    match symbol {
${arms}
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::covalent_radius;

    #[test]
    fn generated_radii_cover_light_halogen_and_heavy_elements() {
        assert_eq!(covalent_radius("H"), Some(0.31));
        assert_eq!(covalent_radius("C"), Some(0.76));
        assert_eq!(covalent_radius("I"), Some(1.39));
        assert_eq!(covalent_radius("Xe"), Some(1.40));
        assert_eq!(covalent_radius("not-an-element"), None);
    }
}
`

const outputFile = resolve(root, outputPath)
if (process.argv.includes(`--check`)) {
  const current = readFileSync(outputFile, `utf8`)
  if (current !== output) {
    throw new Error(`${outputPath} is not up to date`)
  }
} else {
  writeFileSync(outputFile, output)
}
